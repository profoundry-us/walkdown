/*
 * Copy the Phosphor icons we actually use into panel.js, between markers.
 *
 * The panel has to stay one self-contained file — it is delivered both as a
 * <script> tag and as an extension import, and neither can afford a second
 * request or a bundler. So the paths live inline, and this regenerates them
 * rather than anyone hand-pasting SVG.
 *
 *   node tools/sync-phosphor.mjs            # rewrite the block
 *   node tools/sync-phosphor.mjs --check    # fail if it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const HERE = dirname(new URL(import.meta.url).pathname);
const ROOT = join(HERE, '..');
const PANEL = join(ROOT, 'lib', 'viewer', 'panel.js');
const WEIGHT = 'regular';

// Add a name here, run the script, use it as icon('name'). Nothing else.
const USED = ['browser', 'checks', 'folders', 'gear', 'map-pin'];

const START = '  // --- phosphor:start (generated by tools/sync-phosphor.mjs) ---';
const END = '  // --- phosphor:end ---';

const body = (name) => {
  const svg = readFileSync(join(ROOT, 'node_modules', '@phosphor-icons', 'core', 'assets', WEIGHT, `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  if (!inner) throw new Error(`no markup in ${name}.svg`);
  return inner;
};

const block = [
  START,
  `  const PHOSPHOR = {`,
  ...USED.map((n) => `    '${n}': '${body(n).replace(/'/g, "\\'")}',`),
  `  };`,
  END,
].join('\n');

const src = readFileSync(PANEL, 'utf8');
const from = src.indexOf(START);
const to = src.indexOf(END);
if (from < 0 || to < 0) {
  console.error(`markers not found in ${PANEL} — add:\n${START}\n${END}`);
  process.exit(1);
}
const next = src.slice(0, from) + block + src.slice(to + END.length);

if (process.argv.includes('--check')) {
  if (next !== src) {
    console.error('panel.js icons are out of date — run: node tools/sync-phosphor.mjs');
    process.exit(1);
  }
  console.log(`icons up to date (${USED.length})`);
} else {
  writeFileSync(PANEL, next);
  console.log(`synced ${USED.length} icon(s) from @phosphor-icons/core/${WEIGHT}`);
}
