/*
 * Copy the Phosphor icons we actually use into panel.js, between markers.
 *
 * The panel has to stay one self-contained file — it is delivered both as a
 * <script> tag and as an extension import, and neither can afford a second
 * request or a bundler. So the paths live inline, and this regenerates them
 * rather than anyone hand-pasting SVG.
 *
 *   node tools/sync-phosphor.mjs            # rewrite the block
 *   node tools/sync-phosphor.mjs --check    # fail if it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const HERE = dirname(new URL(import.meta.url).pathname);
const ROOT = join(HERE, '..');
const PANEL = join(ROOT, 'lib', 'viewer', 'panel.js');
const EMBED = join(ROOT, 'lib', 'viewer', 'embed.js');

/*
 * Who needs which icons. The embed is injected into every page walkdown looks
 * at, so it carries only what it draws - one pin - rather than the panel's
 * whole set. A filled weight is keyed with its suffix, the way Phosphor names
 * it, so `map-pin` and `map-pin-fill` can both exist.
 */
const TARGETS = [
  { file: PANEL, icons: [['bounding-box', 'regular'], ['checks', 'regular'], ['desktop', 'regular'],
    ['device-mobile', 'regular'], ['frame-corners', 'regular'], ['gear', 'regular'], ['map-pin', 'regular']] },
  { file: EMBED, icons: [['map-pin', 'fill']] },
];

const START = '  // --- phosphor:start (generated by tools/sync-phosphor.mjs) ---';
const END = '  // --- phosphor:end ---';

const key = (name, weight) => (weight === 'regular' ? name : `${name}-${weight}`);
const body = (name, weight) => {
  const file = `${key(name, weight)}.svg`;
  const svg = readFileSync(join(ROOT, 'node_modules', '@phosphor-icons', 'core', 'assets', weight, file), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  if (!inner) throw new Error(`no markup in ${file}`);
  return inner;
};

const blockFor = (icons) => [
  START,
  `  const PHOSPHOR = {`,
  ...icons.map(([n, w]) => `    '${key(n, w)}': '${body(n, w).replace(/'/g, "\\'")}',`),
  `  };`,
  END,
].join('\n');

const check = process.argv.includes('--check');
let stale = 0;
for (const target of TARGETS) {
  const src = readFileSync(target.file, 'utf8');
  const from = src.indexOf(START);
  const to = src.indexOf(END);
  if (from < 0 || to < 0) {
    console.error(`markers not found in ${target.file} — add:\n${START}\n${END}`);
    process.exit(1);
  }
  const next = src.slice(0, from) + blockFor(target.icons) + src.slice(to + END.length);
  if (next === src) continue;
  stale += 1;
  if (!check) writeFileSync(target.file, next);
  console.log(`${check ? 'stale' : 'synced'}: ${target.file} (${target.icons.length} icon(s))`);
}
if (check && stale) {
  console.error('icons are out of date — run: node tools/sync-phosphor.mjs');
  process.exit(1);
}
if (!stale) console.log('icons up to date');
